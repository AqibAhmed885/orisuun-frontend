import fs from "fs";
import path from "path";

const PAGE_FILES = new Set(["page.tsx", "page.ts", "page.jsx", "page.js", "page.mdx"]);
const SITEMAP_ROUTE_PATTERN = /^sitemap(?:-|\.|$)/;

const VALID_USER_TYPES = [
  "black-owned-businesses",
  "professionals",
  "experts",
  "mentors",
  "strategy-consultants",
  "partners",
  "investors",
  "advocates",
];

const INCLUDED_ROUTE_PATHS = [
  "/signin",
  "/signup",
  "/weekly-funding",
  "/weekly-small-business-funding",
  "/weekly-startups-funding",
];

const EXCLUDED_ROUTE_GROUPS = new Set(["(dashboard)", "(landing)"]);
const EXCLUDED_SEGMENTS = new Set([
  "api",
  "admin",
  "components",
  "component",
  "not-found",
  "robots",
  "sitemap.xml",
  "sitemap-index.xml",
  "sitemap-pages.xml",
  "sitemap-blogs.xml",
]);
const EXCLUDED_ROUTE_PREFIXES = [
  "/404",
  "/500",
  "/admin",
  "/dashboard",
  "/signup-thank-you",
  "/free/signup",
  "/free/signup-thank-you",
  "/forgot-password",
  "/reset-password",
  "/payments",
  "/payment",
  "/pdf-preview",
  "/event-pdf",
  "/beta",
  "/new",
  "/discount",
];

function isRouteGroup(segment) {
  return segment.startsWith("(") && segment.endsWith(")");
}

function isDynamicSegment(segment) {
  return segment.startsWith("[") && segment.endsWith("]");
}

function isPrivateOrParallelSegment(segment) {
  return segment.startsWith("_") || segment.startsWith("@");
}

function shouldSkipSegment(segment) {
  return (
    EXCLUDED_SEGMENTS.has(segment) ||
    EXCLUDED_ROUTE_GROUPS.has(segment) ||
    SITEMAP_ROUTE_PATTERN.test(segment) ||
    isPrivateOrParallelSegment(segment) ||
    segment.includes(".backup")
  );
}

function shouldSkipRoute(route) {
  return EXCLUDED_ROUTE_PREFIXES.some(
    (prefix) => route === prefix || route.startsWith(`${prefix}/`),
  );
}

function expandRouteSegments(segments) {
  const routeSegments = segments.filter((segment) => !isRouteGroup(segment));
  const userTypeIndex = routeSegments.indexOf("[userType]");

  if (routeSegments.some((segment) => isDynamicSegment(segment) && segment !== "[userType]")) {
    return [];
  }

  if (userTypeIndex >= 0) {
    return VALID_USER_TYPES.map((userType) => {
      const expanded = [...routeSegments];
      expanded[userTypeIndex] = userType;
      return expanded.length > 0 ? `/${expanded.join("/")}` : "/";
    });
  }

  return [routeSegments.length > 0 ? `/${routeSegments.join("/")}` : "/"];
}

function toRoutePaths(appDir, pageFile) {
  const relativeDir = path.relative(appDir, path.dirname(pageFile));
  const segments = relativeDir.split(path.sep).filter(Boolean);

  if (segments.some(shouldSkipSegment)) {
    return [];
  }

  return expandRouteSegments(segments).filter((routePath) => !shouldSkipRoute(routePath));
}

function walkForPages(dir, appDir, routes) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const fullPath = path.join(dir, entry.name);

    if (entry.isDirectory()) {
      if (!shouldSkipSegment(entry.name) || isRouteGroup(entry.name)) {
        walkForPages(fullPath, appDir, routes);
      }
      continue;
    }

    if (entry.isFile() && PAGE_FILES.has(entry.name)) {
      for (const routePath of toRoutePaths(appDir, fullPath)) {
        routes.add(routePath);
      }
    }
  }
}

function getAppDirectories() {
  const root = process.cwd();
  return [path.join(root, "app"), path.join(root, "src", "app")].filter((dir) =>
    fs.existsSync(dir),
  );
}

function getStaticPageRoutes() {
  const routes = new Set(INCLUDED_ROUTE_PATHS);

  for (const appDir of getAppDirectories()) {
    walkForPages(appDir, appDir, routes);
  }

  return Array.from(routes).sort((a, b) => {
    if (a === "/") return -1;
    if (b === "/") return 1;
    return a.localeCompare(b);
  });
}

const routes = getStaticPageRoutes();
const outputPath = path.join(process.cwd(), "app", "generated-sitemap-routes.ts");
const output = `// This file is generated by scripts/generate-sitemap-routes.mjs.
// Do not edit it by hand.

export const GENERATED_SITEMAP_ROUTES = ${JSON.stringify(routes, null, 2)} as const;
`;

fs.writeFileSync(outputPath, output);
console.info(`Generated ${routes.length} sitemap page routes at ${path.relative(process.cwd(), outputPath)}`);
